package com.volleyballlab.player.data.auth

import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.NoCredentialException
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.volleyballlab.player.R

/**
 * The outcome of asking the system for a Google identity.
 *
 * Cancellation is its own case, not a failure. Dismissing the account sheet is a
 * decision, and answering it with a red error message tells the athlete something
 * went wrong when what actually happened is that they changed their mind.
 */
sealed interface GoogleIdResult {
    data class Success(val idToken: String) : GoogleIdResult
    data object Cancelled : GoogleIdResult
    data class Failure(val messageRes: Int, val cause: Throwable?) : GoogleIdResult
}

/**
 * Fetches a Google ID token through Credential Manager.
 *
 * ## Why Credential Manager and not GoogleSignInClient
 *
 * `play-services-auth`'s `GoogleSignInClient` is the API most tutorials still show,
 * and it is deprecated. Credential Manager is the supported path, it is the one
 * that keeps working as Play Services moves on, and it does not need an
 * `ActivityResultLauncher` threaded through the composable - the call suspends and
 * returns.
 *
 * ## The context has to be an Activity
 *
 * Credential Manager renders a system sheet, so it needs a context that can host
 * one. Passing the application context throws at runtime rather than failing to
 * compile, which is why the parameter is named for what it must be.
 *
 * ## Where the client id comes from
 *
 * `R.string.default_web_client_id` is generated by the Google Services plugin from
 * `app/google-services.json`, and it is the **web** client, not the Android one -
 * a detail that costs people hours, because passing the Android client id produces
 * a token Firebase rejects with no useful explanation. Because it is generated, it
 * cannot drift from the json the way a pasted constant would.
 */
class GoogleCredentialClient(private val webClientId: String) {

    suspend fun requestIdToken(activityContext: Context): GoogleIdResult {
        val option = GetSignInWithGoogleOption.Builder(webClientId).build()
        val request = GetCredentialRequest.Builder().addCredentialOption(option).build()

        return try {
            val response = CredentialManager.create(activityContext)
                .getCredential(activityContext, request)
            val credential = response.credential

            if (credential is CustomCredential &&
                credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
            ) {
                GoogleIdResult.Success(GoogleIdTokenCredential.createFrom(credential.data).idToken)
            } else {
                // Should not happen: the request asked for exactly one option. If it
                // does, something in the credential stack has changed underneath us
                // and guessing at the payload would be worse than saying so.
                GoogleIdResult.Failure(R.string.auth_error_google_unavailable, null)
            }
        } catch (cancelled: GetCredentialCancellationException) {
            GoogleIdResult.Cancelled
        } catch (none: NoCredentialException) {
            // No Google account on the device, or none the picker is willing to
            // offer. Distinct from a failure, because the fix is on the phone rather
            // than in the app, and the message says so.
            GoogleIdResult.Failure(R.string.auth_error_no_google_account, none)
        } catch (failure: Exception) {
            GoogleIdResult.Failure(R.string.auth_error_google_unavailable, failure)
        }
    }
}
